#!/usr/bin/env node
/*
 * Two build steps, run by the GitHub workflow:
 *   node scripts/prepare.js fonts   copies the fonts into www/fonts so the app works offline
 *   node scripts/prepare.js brand   after "cap add android": app icon, splash colour, notification permissions
 * Both steps skip what they cannot find instead of failing the build.
 */
const fs = require('fs');
const path = require('path');

const step = process.argv[2];

function exists(p) { try { fs.accessSync(p); return true; } catch (e) { return false; } }
function walk(dir, fn) {
  if (!exists(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, fn); else fn(p);
  }
}
function copyTree(src, dst) {
  walk(src, (p) => {
    const target = path.join(dst, path.relative(src, p));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(p, target);
  });
}

if (step === 'fonts') {
  const RANGES = {
    hebrew: 'U+0307-0308,U+0590-05FF,U+200C-2010,U+20AA,U+25CC,U+FB1D-FB4F',
    latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
    devanagari: 'U+0900-097F,U+1CD0-1CF9,U+200C-200D,U+20A8,U+20B9,U+20F0,U+25CC,U+A830-A839,U+A8E0-A8FF,U+11B00-11B09'
  };
  const FONTS = [
    { pkg: 'heebo', family: 'Heebo', weights: [300, 400, 500, 700], subsets: ['hebrew', 'latin'] },
    { pkg: 'frank-ruhl-libre', family: 'Frank Ruhl Libre', weights: [400, 500, 700], subsets: ['hebrew', 'latin'] },
    { pkg: 'noto-sans-devanagari', family: 'Noto Sans Devanagari', weights: [400, 500], subsets: ['devanagari'] }
  ];
  const outDir = path.join('www', 'fonts');
  fs.mkdirSync(outDir, { recursive: true });
  let css = '/* generated by scripts/prepare.js */\n';
  let count = 0;
  for (const f of FONTS) {
    for (const w of f.weights) {
      for (const sub of f.subsets) {
        const name = `${f.pkg}-${sub}-${w}-normal.woff2`;
        const src = path.join('node_modules', '@fontsource', f.pkg, 'files', name);
        if (!exists(src)) { console.warn('font file not found, skipped:', name); continue; }
        fs.copyFileSync(src, path.join(outDir, name));
        css += `@font-face { font-family: "${f.family}"; font-style: normal; font-display: swap; font-weight: ${w}; src: url(${name}) format("woff2"); unicode-range: ${RANGES[sub]}; }\n`;
        count++;
      }
    }
  }
  fs.writeFileSync(path.join(outDir, 'fonts.css'), css);
  console.log(`fonts: ${count} files copied`);
} else if (step === 'brand') {
  const res = path.join('android', 'app', 'src', 'main', 'res');
  if (!exists(res)) { console.error('android project not found, run "npx cap add android" first'); process.exit(1); }
  copyTree(path.join('resources', 'res'), res);
  let splashes = 0;
  walk(res, (p) => {
    if (path.basename(p) === 'splash.png') { fs.copyFileSync(path.join('resources', 'splash.png'), p); splashes++; }
  });
  fs.mkdirSync(path.join(res, 'values'), { recursive: true });
  fs.writeFileSync(path.join(res, 'values', 'ic_launcher_background.xml'),
    '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#2D7048</color>\n</resources>\n');
  const manifest = path.join('android', 'app', 'src', 'main', 'AndroidManifest.xml');
  if (exists(manifest)) {
    let m = fs.readFileSync(manifest, 'utf8');
    for (const perm of ['android.permission.POST_NOTIFICATIONS', 'android.permission.SCHEDULE_EXACT_ALARM']) {
      if (!m.includes(perm)) m = m.replace('<application', `<uses-permission android:name="${perm}" />\n    <application`);
    }
    fs.writeFileSync(manifest, m);
  }
  console.log(`brand: icons, ${splashes} splash images, manifest updated`);
} else {
  console.error('usage: node scripts/prepare.js fonts|brand');
  process.exit(1);
}
